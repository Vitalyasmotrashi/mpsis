`timescale 1ns / 1ps

module CYBERcobra (
  input  logic         clk_i,    // Тактовый сигнал
  input  logic         rst_i,    // Сигнал сброса 
  input  logic [15:0]  sw_i,     // Переключатели на плате (внешние данные)
  output logic [31:0]  out_o     // Вывод данных на внешние индикаторы
);

  // =======================================================================
  // ВНУТРЕННИЕ ПРОВОДА (СИГНАЛЫ ДАТАПАТА)
  // =======================================================================
  
  // Программный счетчик (PC)
  logic [31:0] pc_reg;           // Текущий адрес инструкции
  logic [31:0] next_pc;          // Следующий адрес инструкции
  
  // Память инструкций
  logic [31:0] instr;            // 32 бита инструкции, выходящие из памяти
  
  // АЛУ и Регистровый файл
  logic [31:0] rd1_data, rd2_data; // Прочитанные из регистров данные
  logic [31:0] alu_result;       // Выход АЛУ
  logic        alu_flag;         // Флаг АЛУ (сравнение)
  logic[31:0] write_data;       // Данные, которые пойдут на запись в регистр
  logic        rf_we;            // Флаг разрешения записи в регистр (Write Enable)

  // Сигналы расширения и констант
  logic [31:0] const_extended;   // 23-битная константа из инструкции (до 32 бит)
  logic [31:0] offset_extended;  // Смещение для прыжка (с умножением на 4)
  
  // Управляющая логика
  logic        jump_taken;       // Флаг того, что совершается прыжок
  logic [31:0] pc_increment;     // Значение, которое прибавляем к PC (4 или смещение)

  // =======================================================================
  // 1. ДЕКОДИРОВАНИЕ ИНСТРУКЦИИ (Извлечение полей)
  // =======================================================================
  
  logic        J;
  logic        B;
  logic [1:0]  WS;
  logic [4:0]  alu_op;
  logic [4:0]  RA1, RA2, WA;
  
  assign J      = instr[31];       // Бит безусловного перехода (Jump)
  assign B      = instr[30];       // Бит условного перехода (Branch)
  assign WS     = instr[29:28];    // Write Source (что пишем в регистр)
  assign alu_op = instr[27:23];    // Код операции АЛУ
  assign RA1    = instr[22:18];    // Адрес 1-го операнда для чтения
  assign RA2    = instr[17:13];    // Адрес 2-го операнда для чтения
  assign WA     = instr[4:0];      // Адрес для записи результата

  // Знаковое расширение константы (23 бита -> 32 бита)
  assign const_extended = {{9{instr[27]}}, instr[27:5]};

  // Знаковое расширение смещения с умножением на 4 (добавление 2'b00)
  assign offset_extended = {{22{instr[12]}}, instr[12:5], 2'b00};


  // =======================================================================
  // 2. ПРОГРАММНЫЙ СЧЕТЧИК (PC REGISTER)
  // =======================================================================
  
  always_ff @(posedge clk_i) begin
    if (rst_i)
      pc_reg <= 32'd0;  // Сброс в 0
    else
      pc_reg <= next_pc; // Обновление счетчика
  end

  // =======================================================================
  // 3. ПОДКЛЮЧЕНИЕ ПАМЯТИ ИНСТРУКЦИЙ (Твой модуль)
  // =======================================================================
  
  instr_mem imem (
    .read_addr_i (pc_reg),  // Подаем текущий адрес
    .read_data_o (instr)    // Забираем инструкцию
  );

  // =======================================================================
  // 4. ЛОГИКА ПЕРЕХОДОВ И СУММАТОР PC (Твой модуль сумматора)
  // =======================================================================
  
  // Прыгаем, если это Jump ИЛИ это Branch и условие сравнения (alu_flag) истинно
  assign jump_taken = J | (B & alu_flag);
  
  // Выбираем, что прибавлять к PC: смещение (прыжок) или 4 (следующая команда)
  assign pc_increment = jump_taken ? offset_extended : 32'd4;

  // Экземпляр твоего 32-битного сумматора для обновления PC!
  adder_32bit pc_adder (
    .a_i      (pc_reg),       // Первое слагаемое: текущий адрес
    .b_i      (pc_increment), // Второе слагаемое: 4 или смещение
    .carry_i  (1'b0),         // Входной перенос всегда 0
    .sum_o    (next_pc),      // Результат -> следующий адрес
    .carry_o  ()              // Перенос наружу игнорируем
  );

  // =======================================================================
  // 5. ПОДКЛЮЧЕНИЕ РЕГИСТРОВОГО ФАЙЛА (Твой модуль)
  // =======================================================================
  
  // Мы запрещаем писать в регистровый файл во время прыжков (B и J)
  assign rf_we = ~(J | B);

  register_file rf (
    .clk_i          (clk_i),
    .write_enable_i (rf_we),        // Разрешение записи
    .write_addr_i   (WA),           // Адрес записи
    .read_addr1_i   (RA1),          // Читаем операнд 1
    .read_addr2_i   (RA2),          // Читаем операнд 2
    .write_data_i   (write_data),   // То, что выбрали на мультиплексоре WD
    .read_data1_o   (rd1_data),     // Данные 1
    .read_data2_o   (rd2_data)      // Данные 2
  );

  // Прямой вывод содержимого первого прочитанного регистра наружу процессора
  assign out_o = rd1_data;

  // =======================================================================
  // 6. ПОДКЛЮЧЕНИЕ АЛУ (Твой модуль)
  // =======================================================================
  
  alu main_alu (
    .a_i      (rd1_data),   // Левый операнд (из регистра)
    .b_i      (rd2_data),   // Правый операнд (из регистра)
    .alu_op_i (alu_op),     // Опкод (5 бит [27:23])
    .result_o (alu_result), // Результат вычислений
    .flag_o   (alu_flag)    // Флаг результата сравнения
  );

  // =======================================================================
  // 7. МУЛЬТИПЛЕКСОР ЗАПИСИ (WD Mux)
  // =======================================================================
  
  // Управляется 2 битами WS [29:28]
  always_comb begin
    case (WS)
      2'b00: write_data = const_extended;    // Загружаем константу
      2'b01: write_data = alu_result;        // Загружаем результат АЛУ
      2'b10: write_data = {16'd0, sw_i};     // Загружаем с тумблеров платы
      // 2'b11 - по заданию не используется
      default: write_data = 32'd0;           // Дефолт, чтобы избежать защелок (latch)
    endcase
  end

endmodule